def main():

    left_lines = left_side.splitlines()
    right_lines = right_side.splitlines()


    left_elems = len(left_lines)
    right_elems = len(right_lines)
    if left_elems != right_elems:
        print(f"Line Count is not Equal: {left_elems} : {right_elems}")
        return
    
    print(f"Line Count is Equal: {left_elems} : {right_elems}")

    current_line = 0
    for current_line in range(left_elems):
        left_line = left_lines[current_line]
        right_line = right_lines[current_line]
        
        if left_line == ',':
            continue

        left_line_elems = left_line.split(', ')
        right_line_elems = right_line.split(', ')

        left_line_elem_count = len( left_line_elems )
        right_line_elem_count = len( right_line_elems )
        if left_line_elem_count != right_line_elem_count:
            print(f"Inequality at Line {current_line}:  \t{left_line} : {right_line}")
            continue

        for current_line_element in range(left_line_elem_count):
            left_elem = left_line_elems[current_line_element]
            right_elem = right_line_elems[current_line_element]

            if left_elem == right_elem:
                continue

            mapping = mappings.get(left_elem, "no")
            if mapping != "no" and mapping == right_elem:
                continue

            print(f"Inequality at Line {current_line}.{current_line_element}:  \t\"{left_elem}\" : \"{right_elem}\"")
    return


if __name__ == "__main__":
    main()